import { resolve } from 'node:path';
import { expect, test } from '@playwright/test';
import { enterAnonymousLibrary } from './support/onboarding';
import { uploadLibraryFiles } from './support/upload';

test('custom voice IDs persist in defaults and remain drafts in the reader', async ({ page }) => {
  test.setTimeout(75_000);
  await enterAnonymousLibrary(page);
  await page.goto('/app/settings?section=api');
  const originalVoice = (await page.getByRole('button', { name: /^Favorite / }).first()
    .getAttribute('aria-label'))!.slice('Favorite '.length);
  const customVoice = 'custom-voice-check';
  const unsaved = page.getByRole('region', { name: 'Unsaved changes', exact: true });
  await page.getByText('Custom voice ID', { exact: true }).click();
  const field = page.getByRole('textbox', { name: 'Custom voice ID', exact: true });
  await field.fill('');
  await expect(page.getByRole('button', { name: 'Use voice', exact: true })).toBeDisabled();
  await field.fill(customVoice);
  await expect(unsaved).toBeHidden();
  await page.getByRole('button', { name: 'Use voice', exact: true }).click();
  await unsaved.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(unsaved).toBeHidden();
  await page.reload();
  await expect(page.getByRole('button', { name: customVoice, exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByText('Custom voice ID', { exact: true }).click();
  await expect(field).toHaveValue(customVoice);
  await page.setViewportSize({ width: 390, height: 844 });
  await field.scrollIntoViewIfNeeded();
  const useVoice = page.getByRole('button', { name: 'Use voice', exact: true });
  const buttonBox = (await useVoice.boundingBox())!;
  const inputBox = (await field.boundingBox())!;
  expect(buttonBox.x).toBeGreaterThan(inputBox.x + inputBox.width);
  expect(buttonBox.x + buttonBox.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: `/private/tmp/web-custom-voice-${test.info().project.name}.png` });
  await page.getByRole('button', { name: originalVoice, exact: true }).click();
  await unsaved.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(unsaved).toBeHidden();
  await page.getByRole('link', { name: 'Close settings', exact: true }).click();
  await uploadLibraryFiles(page, resolve('tests/files/sample.md'));
  await page.getByRole('link', { name: 'sample.md', exact: true }).click();
  const dockVoice = page.getByRole('button', { name: /^Voice:/ }).first();
  await dockVoice.click();
  const panel = page.getByRole('dialog', { name: 'Voice', exact: true });
  await panel.getByText('Custom voice ID', { exact: true }).click();
  await panel.getByRole('textbox', { name: 'Custom voice ID', exact: true }).fill(customVoice);
  await panel.getByRole('button', { name: 'Use voice', exact: true }).click();
  await expect(panel.getByRole('region', { name: 'Pending voice changes', exact: true })).toContainText(customVoice);
  await panel.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(panel).toBeHidden();
  await expect(dockVoice).toHaveAttribute('aria-label', `Voice: ${originalVoice}`);
  await dockVoice.click();
  await expect(panel.getByRole('region', { name: 'Pending voice changes', exact: true })).toBeHidden();
  await expect(panel.getByRole('button', { name: originalVoice, exact: true })).toHaveAttribute('aria-pressed', 'true');
});
