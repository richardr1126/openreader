import { resolve } from 'node:path';
import { expect, test } from '@playwright/test';
import { enterAnonymousLibrary } from './support/onboarding';
import { uploadLibraryFiles } from './support/upload';

test('favorites and reader appearance persist with independent book inheritance', async ({ page }) => {
  test.setTimeout(75_000);
  await enterAnonymousLibrary(page);
  await page.goto('/app/settings?section=api');
  const star = page.getByRole('button', { name: /^Favorite / }).first();
  await expect(star).toBeVisible();
  const voice = (await star.getAttribute('aria-label'))!.slice('Favorite '.length);
  await star.click();
  await page.getByRole('button', { name: 'Favorites', exact: true }).click();
  await expect(page.getByRole('button', { name: `Remove ${voice} from favorites`, exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.reload();
  await page.getByRole('button', { name: 'Favorites', exact: true }).click();
  await page.getByRole('button', { name: `Remove ${voice} from favorites`, exact: true }).click();
  await expect(page.getByText('No favorite voices for this model.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Show all voices', exact: true }).click();
  await expect(page.getByRole('button', { name: `Favorite ${voice}`, exact: true })).toBeVisible();

  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await page.getByRole('button', { name: 'Font family', exact: true }).click();
  await page.getByRole('option', { name: 'Sans', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Font family', exact: true })).toContainText('Sans');
  const sample = page.getByRole('article', { name: 'Reading sample', exact: true });
  await expect(sample).toHaveCSS('font-family', 'system-ui, sans-serif');
  await expect(page.getByRole('slider', { name: 'Text size', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Increase text size', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: 'Text size', exact: true })).toHaveValue('105');
  await expect.poll(() => sample.evaluate((element) => parseFloat(getComputedStyle(element).fontSize))).toBeCloseTo(14.7, 3);
  await page.getByRole('radiogroup', { name: 'Spacing presets', exact: true }).getByRole('radio', { name: 'Open', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: 'Line spacing', exact: true })).toHaveValue('1.9');
  await expect(page.getByRole('spinbutton', { name: 'Paragraph spacing', exact: true })).toHaveValue('1.5');
  await expect(page.getByRole('spinbutton', { name: 'Letter spacing', exact: true })).toHaveValue('0.03');
  await page.getByRole('button', { name: 'Font family', exact: true }).click();
  await expect(page.getByRole('option', { name: 'Sans', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.screenshot({ path: `/private/tmp/reader-parity-web-settings-${test.info().project.name}.png` });
  await page.keyboard.press('Escape');
  await page.getByRole('link', { name: 'Close settings', exact: true }).click();
  await uploadLibraryFiles(page, resolve('tests/files/sample.md'));
  await page.getByRole('link', { name: 'sample.md', exact: true }).click();
  const text = page.locator('.html-container');
  await expect(text).toHaveCSS('font-family', 'system-ui, sans-serif');
  await expect.poll(() => text.evaluate((element) => parseFloat(getComputedStyle(element).fontSize))).toBeCloseTo(16.8, 3);
  let audioWork = 0;
  page.on('request', (request) => {
    if (/reader-bootstrap|\/api\/tts\/playback/.test(request.url())) audioWork += 1;
  });
  await page.getByRole('button', { name: 'Open settings', exact: true }).click();
  const settings = page.getByRole('dialog', { name: 'Document settings', exact: true });
  const typographySection = settings.locator('section').filter({ has: page.getByRole('heading', { name: 'Typography', exact: true }) });
  const typographyHeight = (await typographySection.boundingBox())!.height;
  await settings.getByRole('button', { name: 'Font family', exact: true }).click();
  await page.getByRole('option', { name: 'Mono', exact: true }).click();
  await expect(text).toHaveCSS('font-family', 'ui-monospace, monospace');
  await expect(sample).toHaveCSS('font-family', 'ui-monospace, monospace');
  expect((await typographySection.boundingBox())!.height).toBe(typographyHeight);
  await expect(settings.getByRole('button', { name: 'Use global fontFamily', exact: true })).toBeVisible();
  await expect(settings.getByText('Use global', { exact: true })).toHaveCount(0);
  const highlightSection = settings.locator('section').filter({ has: page.getByRole('heading', { name: 'Highlight appearance', exact: true }) });
  const highlightHeight = (await highlightSection.boundingBox())!.height;
  await settings.getByRole('radio', { name: 'Ocean', exact: true }).click();
  await expect(text).toHaveCSS('--reader-word-color', '#2563eb');
  expect((await highlightSection.boundingBox())!.height).toBe(highlightHeight);
  await settings.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(settings).toBeHidden();
  expect(audioWork).toBe(0);
  await page.reload();
  await expect(text).toHaveCSS('font-family', 'ui-monospace, monospace');
  await expect(text).toHaveCSS('--reader-word-color', '#2563eb');
  await page.getByRole('button', { name: 'Open settings', exact: true }).click();
  await settings.getByRole('button', { name: 'Use global fontFamily', exact: true }).click();
  await expect(text).toHaveCSS('font-family', 'system-ui, sans-serif');
  await expect(text).toHaveCSS('--reader-word-color', '#2563eb');
  await settings.getByRole('button', { name: 'Use global highlights', exact: true }).click();
  await expect(text).toHaveCSS('--reader-word-color', '');
});
