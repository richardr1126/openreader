import { resolve } from 'node:path';
import { expect, test } from '@playwright/test';
import { enterAnonymousLibrary } from './support/onboarding';
import { uploadLibraryFiles } from './support/upload';

test('speech defaults and independent book overrides persist without changing displayed text', async ({ page }) => {
  test.setTimeout(75_000);
  await enterAnonymousLibrary(page);
  await page.goto('/app/settings?section=api');
  const citations = page.getByRole('switch', { name: 'Skip citations', exact: true });
  const brackets = page.getByRole('button', { name: 'Skip bracketed text', exact: true });
  const voiceSection = page.getByRole('region', { name: 'Model & Voice', exact: true }).locator('section')
    .filter({ has: page.getByRole('heading', { name: 'Default voice', exact: true }) });
  const skipHeading = page.getByRole('heading', { name: 'Skip when reading aloud', exact: true });
  const voiceBounds = (await voiceSection.boundingBox())!;
  expect((await skipHeading.boundingBox())!.y).toBeGreaterThanOrEqual(voiceBounds.y + voiceBounds.height);
  const citationHelp = page.getByRole('button', { name: 'About Citations', exact: true });
  await citationHelp.click();
  await expect(page.getByText(/^Skip numeric references such as/)).toBeVisible();
  await citationHelp.click();
  await expect(page.getByText(/^Skip numeric references such as/)).toBeHidden();
  await expect(citations).toHaveAttribute('aria-checked', 'false');
  await expect(brackets).toContainText('Off');
  await citations.click();
  await brackets.click();
  await page.getByRole('option', { name: 'Both', exact: true }).click();
  await page.getByRole('region', { name: 'Unsaved changes', exact: true }).getByRole('button', { name: 'Save', exact: true }).click();
  await page.reload();
  await expect(citations).toHaveAttribute('aria-checked', 'true');
  await expect(brackets).toContainText('Both');
  await page.getByRole('link', { name: 'Close settings', exact: true }).click();
  await uploadLibraryFiles(page, resolve('tests/files/sample.md'));
  await page.getByRole('link', { name: 'sample.md', exact: true }).click();
  const text = page.locator('.html-container');
  await expect(text).toBeVisible();
  const original = await text.innerText();
  await page.getByRole('button', { name: 'Open settings', exact: true }).click();
  await expect(citations).toHaveAttribute('aria-checked', 'true');
  await expect(brackets).toContainText('Both');
  await citations.click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(citations).toHaveAttribute('aria-checked', 'true');
  await citations.click();
  await page.getByRole('button', { name: 'Change and regenerate', exact: true }).click();
  await expect(citations).toHaveAttribute('aria-checked', 'false');
  await expect(brackets).toContainText('Both');
  await page.reload();
  await page.getByRole('button', { name: 'Open settings', exact: true }).click();
  await expect(citations).toHaveAttribute('aria-checked', 'false');
  await expect(brackets).toContainText('Both');
  await page.getByRole('button', { name: 'Use app default for citations', exact: true }).click();
  await page.getByRole('button', { name: 'Change and regenerate', exact: true }).click();
  await expect(citations).toHaveAttribute('aria-checked', 'true');
  await expect(page.getByRole('button', { name: 'Use app default for citations', exact: true })).toHaveCount(0);
  await expect(text).toHaveText(original, { useInnerText: true });
  await page.screenshot({ path: `/private/tmp/speech-text-web-${test.info().project.name}.png` });
});
